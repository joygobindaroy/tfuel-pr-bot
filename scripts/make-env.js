#!/usr/bin/env node
/**
 * Builds .env.local from your Firebase service account JSON.
 *
 * Usage:
 *   1. Put the service account .json file in this project folder.
 *   2. Run:  node scripts/make-env.js            (or: npm run make-env)
 *      Or:   node scripts/make-env.js path/to/key.json
 *   3. Answer the questions (press Enter to keep a shown value or skip).
 *
 * Existing values in .env.local are kept, so WEBHOOK_SECRET and HASH_SALT
 * never change by accident (changing HASH_SALT breaks stored device hashes).
 *
 * DELETE the service account .json before you upload anything to GitHub.
 */
const fs = require("fs");
const path = require("path");
const crypto = require("crypto");
const readline = require("readline");

const root = path.join(__dirname, "..");
const envPath = path.join(root, ".env.local");

function findKeyFile() {
  const arg = process.argv[2];
  if (arg) return path.resolve(arg);
  const files = fs
    .readdirSync(root)
    .filter((f) => f.endsWith(".json") && /adminsdk|service|firebase/i.test(f));
  if (files.length === 0) return null;
  if (files.length > 1) console.log("Several key files found, using:", files[0]);
  return path.join(root, files[0]);
}

function readExisting() {
  const out = {};
  if (!fs.existsSync(envPath)) return out;
  for (const line of fs.readFileSync(envPath, "utf8").split(/\r?\n/)) {
    const m = line.match(/^([A-Z0-9_]+)=(.*)$/);
    if (!m) continue;
    let v = m[2];
    if (v.startsWith('"') && v.endsWith('"')) v = v.slice(1, -1);
    out[m[1]] = v;
  }
  return out;
}

(async () => {
  const keyFile = findKeyFile();
  if (!keyFile || !fs.existsSync(keyFile)) {
    console.error("Service account .json not found. Put it in this folder or pass its path.");
    process.exit(1);
  }

  let key;
  try {
    key = JSON.parse(fs.readFileSync(keyFile, "utf8"));
  } catch {
    console.error("Could not read that file as JSON.");
    process.exit(1);
  }
  if (!key.project_id || !key.client_email || !key.private_key) {
    console.error("This does not look like a Firebase service account key.");
    process.exit(1);
  }

  const old = readExisting();
  const rl = readline.createInterface({ input: process.stdin });
  const input = rl[Symbol.asyncIterator]();
  const ask = async (label, current) => {
    const hint = current ? ` [${current}]` : "";
    process.stdout.write(`${label}${hint}: `);
    const { value, done } = await input.next();
    const a = done ? "" : String(value).trim();
    return a || current || "";
  };

  console.log("\nFirebase values found. Now the rest:\n");
  const BOT_TOKEN = await ask("BOT_TOKEN (from @BotFather)", old.BOT_TOKEN);
  const ADMIN_IDS = await ask("ADMIN_IDS (your Telegram id, comma separated)", old.ADMIN_IDS);
  const APP_URL = (await ask("APP_URL (https://your-app.vercel.app, no trailing slash)", old.APP_URL)).replace(/\/$/, "");
  const IPQS_API_KEY = await ask("IPQS_API_KEY (ipqualityscore.com)", old.IPQS_API_KEY);
  const UPSTASH_REDIS_REST_URL = await ask("UPSTASH_REDIS_REST_URL (optional, rate limiting)", old.UPSTASH_REDIS_REST_URL);
  const UPSTASH_REDIS_REST_TOKEN = await ask("UPSTASH_REDIS_REST_TOKEN (optional)", old.UPSTASH_REDIS_REST_TOKEN);
  const BINANCE_PAY_API_KEY = await ask("BINANCE_PAY_API_KEY (optional, USDT deposits)", old.BINANCE_PAY_API_KEY);
  const BINANCE_PAY_SECRET = await ask("BINANCE_PAY_SECRET (optional)", old.BINANCE_PAY_SECRET);
  const ADMIN_ALERT_CHAT_ID = await ask("ADMIN_ALERT_CHAT_ID (optional, alerts chat id)", old.ADMIN_ALERT_CHAT_ID);
  rl.close();

  const WEBHOOK_SECRET = old.WEBHOOK_SECRET || crypto.randomBytes(32).toString("hex");
  const HASH_SALT = old.HASH_SALT || crypto.randomBytes(32).toString("hex");
  const CRON_SECRET = old.CRON_SECRET || crypto.randomBytes(32).toString("hex");
  const privateKey = key.private_key.replace(/\r?\n/g, "\\n");

  const lines = [
    "# Generated by scripts/make-env.js. Never commit this file.",
    `BOT_TOKEN=${BOT_TOKEN}`,
    `WEBHOOK_SECRET=${WEBHOOK_SECRET}`,
    `ADMIN_IDS=${ADMIN_IDS}`,
    `APP_URL=${APP_URL}`,
    `FIREBASE_PROJECT_ID=${key.project_id}`,
    `FIREBASE_CLIENT_EMAIL=${key.client_email}`,
    `FIREBASE_PRIVATE_KEY="${privateKey}"`,
    `IPQS_API_KEY=${IPQS_API_KEY}`,
    `HASH_SALT=${HASH_SALT}`,
    `CRON_SECRET=${CRON_SECRET}`,
    `ADMIN_ALERT_CHAT_ID=${ADMIN_ALERT_CHAT_ID}`,
    `UPSTASH_REDIS_REST_URL=${UPSTASH_REDIS_REST_URL}`,
    `UPSTASH_REDIS_REST_TOKEN=${UPSTASH_REDIS_REST_TOKEN}`,
    `BINANCE_PAY_API_KEY=${BINANCE_PAY_API_KEY}`,
    `BINANCE_PAY_SECRET=${BINANCE_PAY_SECRET}`,
    "",
  ];
  fs.writeFileSync(envPath, lines.join("\n"), { mode: 0o600 });

  console.log("\nWrote .env.local");
  const missing = Object.entries({ BOT_TOKEN, ADMIN_IDS, APP_URL, IPQS_API_KEY })
    .filter(([, v]) => !v)
    .map(([k]) => k);
  if (missing.length) console.log("Still empty:", missing.join(", "));
  console.log("\nNext:");
  console.log("  - Locally this file is used automatically (npm run dev).");
  console.log("  - On Vercel, paste its contents into Settings > Environment Variables (Import .env).");
  console.log("  - Delete the service account .json and .env.local before sharing or uploading the folder.");
})();
